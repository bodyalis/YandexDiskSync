function detectLang(): typeof en {
    try {
        const lang = window.localStorage.getItem('language');
        if (lang === 'ru') return ru;
    } catch {
        /* localStorage may be unavailable on some platforms */
    }
    return en;
}

const currentLang: typeof en = detectLang();

export type I18nKey = keyof typeof en;

export function t(key: I18nKey, ...args: (string | number)[]): string {
    let text: string = currentLang[key] ?? en[key];
    args.forEach((arg, i) => {
        text = text.replace(`{${i}}`, String(arg));
    });
    return text;
}
